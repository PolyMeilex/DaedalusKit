use std::io::Write;

use byteorder::{LittleEndian, WriteBytesExt};
use dat_file::{
    Symbol, SymbolData,
    properties::{DataType, ElemProps, PropFlag, Properties, SymbolCodeSpan},
};
use zstring::{ByteVec, ZString};

use crate::symbol_indices::SymbolIndices;

#[derive(Debug)]
pub struct DatSymbolTable {
    symbols: Vec<Symbol>,
    generated_symbols_start: usize,
    autogenerated_symbols: Vec<Symbol>,
}

impl DatSymbolTable {
    pub fn new(symbol_indices: &SymbolIndices) -> Self {
        let mut this = Self {
            symbols: Vec::with_capacity(symbol_indices.len()),
            generated_symbols_start: symbol_indices.len(),
            autogenerated_symbols: Vec::new(),
        };

        this.push_symbol(Symbol {
            name: Some(ZString::from(b"\xFFINSTANCE_HELP")),
            props: Properties {
                off_cls_ret: 0,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(1);
                    default.set_data_type(DataType::Instance);
                    default.set_flags(PropFlag::empty());
                    default.set_space(1);
                    default
                },
            },
            code_span: SymbolCodeSpan::empty(0),
            data: SymbolData::Address(0),
            parent: None,
        });

        this
    }

    /// "abc"
    pub fn string(&mut self, value: ZString) -> u32 {
        let symbol_id = 10000 + self.autogenerated_symbols.len();
        let mut symbol_str = format!("{symbol_id}").into_bytes();
        symbol_str.insert(0, 0xFF);

        let id = self.generated_symbols_start + self.autogenerated_symbols.len();
        self.autogenerated_symbols.push(Symbol {
            name: Some(ZString::from(symbol_str)),
            props: Properties {
                off_cls_ret: 0,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(1);
                    default.set_data_type(DataType::String);
                    default.set_flags(PropFlag::CONST);
                    default.set_space(1);
                    default
                },
            },
            code_span: SymbolCodeSpan::empty(0),
            data: SymbolData::String(vec![value]),
            parent: None,
        });

        id as u32
    }

    /// extern func void name((var type PARN)*)
    pub fn extern_func(
        &mut self,
        name: ZString,
        span: SymbolCodeSpan,
        args: &[(ZString, DataType, SymbolCodeSpan)],
        ret: DataType,
        address: i32,
    ) -> u32 {
        let fn_symbol = self.push_symbol(Symbol {
            name: Some(name.clone()),
            props: Properties {
                off_cls_ret: ret as i32,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(args.len() as u32);
                    default.set_data_type(DataType::Func);
                    let mut flags = PropFlag::CONST | PropFlag::EXTERNAL;
                    if ret != DataType::Void {
                        flags |= PropFlag::RETURN;
                    }
                    default.set_flags(flags);
                    default.set_space(1);
                    default
                },
            },
            code_span: span,
            data: SymbolData::Address(address),
            parent: None,
        });

        for (ident, arg, span) in args.iter() {
            let mut name = name.clone();
            name.0.push_char('.');
            name.0.push_str(ident);

            self.push_symbol(Symbol {
                name: Some(name),
                props: Properties {
                    off_cls_ret: 0,
                    elem_props: {
                        let mut default = ElemProps::default();
                        default.set_count(0);
                        default.set_data_type(*arg);
                        default.set_flags(PropFlag::empty());
                        default.set_space(1);
                        default
                    },
                },
                code_span: *span,
                data: match arg {
                    DataType::Float => SymbolData::Float(vec![]),
                    DataType::Int => SymbolData::Int(vec![]),
                    DataType::String => SymbolData::String(vec![]),
                    DataType::Class => SymbolData::ClassOffset(0),
                    DataType::Func => SymbolData::Address(0),
                    DataType::Prototype => SymbolData::Address(0),
                    DataType::Instance => SymbolData::Address(0),
                    DataType::Void => SymbolData::None,
                },
                parent: None,
            });
        }

        fn_symbol
    }

    /// func void name((var type PARN)*)
    pub fn func(
        &mut self,
        name: ZString,
        span: SymbolCodeSpan,
        param_count: u32,
        ret: DataType,
        address: u32,
    ) -> u32 {
        let mut flags = PropFlag::CONST;
        if ret != DataType::Void {
            flags |= PropFlag::RETURN;
        }

        self.push_symbol(Symbol {
            name: Some(name),
            props: Properties {
                off_cls_ret: ret as i32,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(param_count);
                    default.set_data_type(DataType::Func);
                    default.set_flags(flags);
                    default.set_space(1);
                    default
                },
            },
            code_span: span,
            data: SymbolData::Address(address as i32),
            parent: None,
        })
    }

    /// Class and its fields, `offset` is where the fields start in the engine object
    pub fn class(
        &mut self,
        name: ZString,
        span: SymbolCodeSpan,
        fields: &[(ZString, DataType, u32, SymbolCodeSpan)],
        offset: u32,
    ) -> u32 {
        let field_size = |data_type: DataType| match data_type {
            DataType::Float | DataType::Int | DataType::Func => 4,
            // class zSTRING { int allocater; char* vector; int length; int reserved; }
            DataType::String => 20,
            DataType::Void | DataType::Class | DataType::Prototype | DataType::Instance => {
                unreachable!("{data_type:?} is not a valid class field type")
            }
        };

        let size: u32 = fields
            .iter()
            .map(|(_, data_type, count, _)| count * field_size(*data_type))
            .sum();

        let class_symbol = self.push_symbol(Symbol {
            name: Some(name.clone()),
            props: Properties {
                off_cls_ret: size as i32,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(fields.len() as u32);
                    default.set_data_type(DataType::Class);
                    default.set_flags(PropFlag::empty());
                    default.set_space(1);
                    default
                },
            },
            code_span: span,
            data: SymbolData::ClassOffset(offset),
            parent: None,
        });

        let mut field_offset = offset;
        for (ident, data_type, count, span) in fields.iter() {
            let mut name = name.clone();
            name.0.push_char('.');
            name.0.push_str(ident);

            self.push_symbol(Symbol {
                name: Some(name),
                props: Properties {
                    off_cls_ret: field_offset as i32,
                    elem_props: {
                        let mut default = ElemProps::default();
                        default.set_count(*count);
                        default.set_data_type(*data_type);
                        default.set_flags(PropFlag::CLASS_VAR);
                        default.set_space(1);
                        default
                    },
                },
                code_span: *span,
                data: SymbolData::None,
                parent: Some(class_symbol),
            });

            field_offset += count * field_size(*data_type);
        }

        class_symbol
    }

    pub fn const_item(
        &mut self,
        name: ZString,
        code_span: SymbolCodeSpan,
        data_type: DataType,
        data: SymbolData,
    ) -> u32 {
        let count = match &data {
            SymbolData::Int(v) => v.len(),
            SymbolData::Float(v) => v.len(),
            SymbolData::String(v) => v.len(),
            _ => unreachable!("constants hold values"),
        };

        self.push_symbol(Symbol {
            name: Some(name),
            props: Properties {
                off_cls_ret: 0,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(count as u32);
                    default.set_data_type(data_type);
                    default.set_flags(PropFlag::CONST);
                    default.set_space(1);
                    default
                },
            },
            code_span,
            data,
            parent: None,
        })
    }

    pub fn var(
        &mut self,
        name: ZString,
        code_span: SymbolCodeSpan,
        data_type: DataType,
        count: u32,
        parent: Option<u32>,
    ) -> u32 {
        let len = count as usize;
        let data = match data_type {
            DataType::Int => SymbolData::Int(vec![0; len]),
            DataType::Float => SymbolData::Float(vec![0.0; len]),
            DataType::String => SymbolData::String(vec![ZString::default(); len]),
            DataType::Instance | DataType::Func => SymbolData::Address(0),
            DataType::Void | DataType::Class | DataType::Prototype => {
                unreachable!("{data_type:?} is not a valid variable type")
            }
        };

        self.push_symbol(Symbol {
            name: Some(name),
            props: Properties {
                off_cls_ret: 0,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(count);
                    default.set_data_type(data_type);
                    default.set_flags(PropFlag::empty());
                    default.set_space(1);
                    default
                },
            },
            code_span,
            data,
            parent,
        })
    }

    pub fn instance(
        &mut self,
        name: ZString,
        code_span: SymbolCodeSpan,
        address: u32,
        parent: u32,
    ) -> u32 {
        self.push_symbol(Symbol {
            name: Some(name),
            props: Properties {
                off_cls_ret: 0,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(0);
                    default.set_data_type(DataType::Instance);
                    default.set_flags(PropFlag::CONST);
                    default.set_space(1);
                    default
                },
            },
            code_span,
            data: SymbolData::Address(address as i32),
            parent: Some(parent),
        })
    }

    pub fn prototype(
        &mut self,
        name: ZString,
        code_span: SymbolCodeSpan,
        address: u32,
        parent: u32,
    ) -> u32 {
        self.push_symbol(Symbol {
            name: Some(name),
            props: Properties {
                off_cls_ret: 0,
                elem_props: {
                    let mut default = ElemProps::default();
                    default.set_count(0);
                    default.set_data_type(DataType::Prototype);
                    default.set_flags(PropFlag::empty());
                    default.set_space(1);
                    default
                },
            },
            code_span,
            data: SymbolData::Address(address as i32),
            parent: Some(parent),
        })
    }

    fn generate_sort_table(&self) -> Vec<u32> {
        let mut symbol_ids: Vec<_> = self
            .symbols
            .iter()
            .chain(self.autogenerated_symbols.iter())
            .enumerate()
            .map(|(i, s)| (i, &s.name))
            .collect();

        // Symbols map is sorted in alphabetical order
        symbol_ids.sort_by_key(|v| v.1.as_slice());
        symbol_ids.iter().map(|(id, _)| *id as u32).collect()
    }

    pub fn push_symbol(&mut self, symbol: Symbol) -> u32 {
        let id = self.symbols.len();
        self.symbols.push(symbol);
        id as u32
    }

    /// Number of symbols defined by the scripts, excluding autogenerated ones
    pub fn len(&self) -> usize {
        self.symbols.len()
    }

    /// Symbol with a given id, unless it failed to compile
    pub fn get(&self, id: u32) -> Option<&Symbol> {
        self.symbols
            .get(id as usize)
            .filter(|symbol| symbol.name.is_some())
    }

    /// After an item failed to compile, drop the symbols it partially emitted, and fill its slots
    /// with unnamed placeholders, so that ids of later symbols still match [`SymbolIndices`]
    pub fn recover_to(&mut self, len: usize) {
        self.symbols.truncate(len);
        self.symbols.resize_with(len, || Symbol {
            name: None,
            props: Properties {
                off_cls_ret: 0,
                elem_props: ElemProps::default(),
            },
            code_span: SymbolCodeSpan::empty(0),
            data: SymbolData::None,
            parent: None,
        });
    }

    pub fn encode(&self, mut w: impl Write) {
        let sort_idx = self.generate_sort_table();

        w.write_u8(b'2').unwrap();
        w.write_u32::<LittleEndian>(
            self.symbols.len() as u32 + self.autogenerated_symbols.len() as u32,
        )
        .unwrap();

        for id in sort_idx.iter() {
            w.write_u32::<LittleEndian>(*id).unwrap();
        }

        for symbol in self.symbols.iter() {
            symbol.encode(&mut w).unwrap();
        }

        for symbol in self.autogenerated_symbols.iter() {
            symbol.encode(&mut w).unwrap();
        }
    }
}
